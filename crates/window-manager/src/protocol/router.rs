//! Pure in-memory message router.
//!
//! The router owns no sockets: a caller feeds it decoded [`Envelope`]s and
//! drains per-peer outboxes. All delivery, correlation, retention and timeout
//! policy lives here so it can be tested without an event loop.

use std::collections::{HashMap, HashSet};
use std::time::{Duration, Instant};

use common::protocol::{
    BusError, BusErrorCode, Control, Envelope, Kind, MessageId, PeerId, PeerName, Target, Topic,
};

/// Deadline for a request waiting on a peer response.
const REQUEST_TIMEOUT: Duration = Duration::from_secs(10);
/// Default lifetime of an event queued for an unknown peer.
const OFFLINE_TTL: Duration = Duration::from_secs(30);
/// Default lifetime of a retained topic value.
const RETAINED_TTL: Duration = Duration::from_secs(30);
/// Maximum number of queued events per absent peer.
pub(crate) const OFFLINE_LIMIT: usize = 32;
/// Source stamped on frames generated by the router itself.
const ROUTER_SOURCE: &str = "router";
/// Topic carrying peer presence notifications.
pub(crate) const PEERS_TOPIC: &str = "bus/peers";

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum State {
    AwaitingHello,
    Ready,
    Closing,
}

#[derive(Debug)]
struct Peer {
    name: Option<PeerName>,
    state: State,
    subscriptions: HashSet<Topic>,
    outbox: Vec<Envelope>,
}

#[derive(Debug)]
pub(crate) struct Pending {
    origin: PeerId,
    origin_name: PeerName,
    target_name: PeerName,
    started: Instant,
}

#[derive(Debug)]
struct Offline {
    envelope: Envelope,
    expires_at: Instant,
}

#[derive(Debug, Clone)]
struct Retained {
    envelope: Envelope,
    expires_at: Instant,
}

/// State machine that routes envelopes between registered peers.
#[derive(Debug)]
pub struct Router {
    next_peer_id: PeerId,
    next_message_id: MessageId,
    peers: HashMap<PeerId, Peer>,
    names: HashMap<PeerName, PeerId>,
    pub(crate) pending: HashMap<(PeerId, MessageId), Pending>,
    retained: HashMap<Topic, Retained>,
    offline: HashMap<PeerName, Vec<Offline>>,
}

impl Default for Router {
    fn default() -> Self {
        Self::new()
    }
}

impl Router {
    /// Creates an empty router.
    pub fn new() -> Self {
        Self {
            next_peer_id: 1,
            next_message_id: 1,
            peers: HashMap::new(),
            names: HashMap::new(),
            pending: HashMap::new(),
            retained: HashMap::new(),
            offline: HashMap::new(),
        }
    }

    /// Allocates a connection that must start with a `Hello` frame.
    pub fn add_connection(&mut self) -> PeerId {
        self.insert_peer(None)
    }

    /// Pre-registers a peer that skips the handshake, such as the WM socket.
    ///
    /// # Arguments
    /// * `name` - Name to reserve for the local peer.
    pub fn register_local(&mut self, name: PeerName) -> PeerId {
        let id = self.insert_peer(Some(name.clone()));
        self.names.insert(name, id);
        id
    }

    /// Allocates a connection, starting it ready when a name is supplied.
    ///
    /// # Arguments
    /// * `name` - Name to pre-register, or `None` to await a handshake.
    ///
    /// # Returns
    /// The id assigned to the new connection.
    fn insert_peer(&mut self, name: Option<PeerName>) -> PeerId {
        let id = self.next_peer_id;
        self.next_peer_id = self.next_peer_id.wrapping_add(1);
        let state = if name.is_some() {
            State::Ready
        } else {
            State::AwaitingHello
        };
        self.peers.insert(
            id,
            Peer {
                name,
                state,
                subscriptions: HashSet::new(),
                outbox: Vec::new(),
            },
        );
        id
    }

    /// Completes the handshake of an awaiting connection.
    ///
    /// On success a `Welcome` frame is queued and `PeerJoined` is published on
    /// `bus/peers`. On a duplicate name an `Error` frame is queued and the
    /// connection is marked for removal.
    ///
    /// # Arguments
    /// * `id` - Connection allocated by [`Self::add_connection`].
    /// * `name` - Requested peer name.
    ///
    /// # Errors
    /// Returns [`BusErrorCode::NameTaken`], [`BusErrorCode::PeerUnavailable`]
    /// for an unknown connection, or [`BusErrorCode::InvalidPayload`] when the
    /// connection already completed its handshake.
    pub fn hello(&mut self, id: PeerId, name: PeerName) -> Result<(), BusError> {
        self.validate_handshake(id)?;
        self.check_name(id, &name)?;
        let welcome = self.welcome_frame(&name)?;
        if let Some(peer) = self.peers.get_mut(&id) {
            peer.name = Some(name.clone());
            peer.state = State::Ready;
            peer.outbox.push(welcome);
        }
        self.names.insert(name.clone(), id);
        self.flush_offline(id, &name);
        self.publish_control(
            Topic::from(PEERS_TOPIC),
            Control::PeerJoined { name },
            Some(id),
        );
        Ok(())
    }

    /// Checks that a connection is still awaiting its handshake.
    ///
    /// # Arguments
    /// * `id` - Connection to validate.
    ///
    /// # Errors
    /// Returns [`BusErrorCode::InvalidPayload`] after a completed handshake, or
    /// [`BusErrorCode::PeerUnavailable`] for an unknown or closing connection.
    fn validate_handshake(&self, id: PeerId) -> Result<(), BusError> {
        match self.peers.get(&id).map(|peer| peer.state) {
            Some(State::AwaitingHello) => Ok(()),
            Some(State::Ready) => Err(BusError::new(
                BusErrorCode::InvalidPayload,
                "peer already completed the handshake",
            )),
            _ => Err(BusError::new(
                BusErrorCode::PeerUnavailable,
                "unknown or closing connection",
            )),
        }
    }

    /// Rejects a name already owned by another connection.
    ///
    /// # Arguments
    /// * `id` - Connection requesting the name.
    /// * `name` - Requested peer name.
    ///
    /// # Errors
    /// Returns [`BusErrorCode::NameTaken`] and marks the connection as closing
    /// when another connection already owns the name.
    fn check_name(&mut self, id: PeerId, name: &PeerName) -> Result<(), BusError> {
        let Some(owner) = self.names.get(name).copied() else {
            return Ok(());
        };
        let error = BusError::new(
            BusErrorCode::NameTaken,
            format!("peer name '{name}' is already used by connection {owner}"),
        );
        self.reject(id, name.clone(), error.clone(), 0);
        if let Some(peer) = self.peers.get_mut(&id) {
            peer.state = State::Closing;
        }
        Err(error)
    }

    /// Builds the `Welcome` reply listing all registered peers.
    ///
    /// # Arguments
    /// * `name` - Name accepted for the new peer.
    ///
    /// # Returns
    /// A router-generated response envelope.
    ///
    /// # Errors
    /// Returns [`BusErrorCode::InvalidPayload`] when serialization fails.
    fn welcome_frame(&mut self, name: &PeerName) -> Result<Envelope, BusError> {
        let payload = serde_json::to_value(Control::Welcome {
            name: name.clone(),
            peers: self.peers_list(),
        })
        .map_err(|error| BusError::new(BusErrorCode::InvalidPayload, error.to_string()))?;
        Ok(self.generated(Target::Router, Kind::Response, payload))
    }

    /// Removes a connection and notifies peers waiting on it.
    ///
    /// # Arguments
    /// * `id` - Connection to remove.
    pub fn remove(&mut self, id: PeerId) {
        let Some(peer) = self.peers.remove(&id) else {
            return;
        };
        self.release_name(id, peer.name.as_ref());
        self.fail_pending(id);
        if let Some(name) = peer.name {
            self.publish_control(
                Topic::from(PEERS_TOPIC),
                Control::PeerLeft { name },
                Some(id),
            );
        }
    }

    /// Unregisters a name when the departing connection still owns it.
    ///
    /// # Arguments
    /// * `id` - Departing connection.
    /// * `name` - Name it registered, if any.
    fn release_name(&mut self, id: PeerId, name: Option<&PeerName>) {
        let Some(name) = name else {
            return;
        };
        if self.names.get(name) == Some(&id) {
            self.names.remove(name);
        }
    }

    /// Rejects pending requests involving a departing connection.
    ///
    /// # Arguments
    /// * `id` - Departing connection.
    fn fail_pending(&mut self, id: PeerId) {
        let keys: Vec<(PeerId, MessageId)> = self
            .pending
            .keys()
            .filter(|(target, origin)| *target == id || *origin == id)
            .copied()
            .collect();
        for key in keys {
            if let Some(pending) = self.pending.remove(&key) {
                if pending.origin != id {
                    let error = BusError::new(
                        BusErrorCode::PeerUnavailable,
                        format!("peer '{}' disconnected", pending.target_name),
                    );
                    self.reject(pending.origin, pending.origin_name, error, key.1);
                }
            }
        }
    }

    /// Feeds one decoded frame into the state machine.
    ///
    /// # Arguments
    /// * `from` - Connection that sent the frame.
    /// * `envelope` - Frame to route; its `source` is overwritten.
    pub fn route(&mut self, from: PeerId, mut envelope: Envelope) {
        let Some((state, origin_name)) = self.validate_frame(from, &envelope) else {
            return;
        };
        if state == State::AwaitingHello {
            self.route_hello(from, &origin_name, &envelope);
            return;
        }
        envelope.source = origin_name.clone();
        self.route_ready(from, origin_name, envelope);
    }

    /// Validates the sender connection and the frame's protocol version.
    ///
    /// # Arguments
    /// * `from` - Connection that sent the frame.
    /// * `envelope` - Frame to validate.
    ///
    /// # Returns
    /// The sender's state and name when routing may continue, or `None` after
    /// the frame was silently dropped or answered with an error frame.
    fn validate_frame(&mut self, from: PeerId, envelope: &Envelope) -> Option<(State, PeerName)> {
        let (state, name) = match self.peers.get(&from) {
            Some(peer) if peer.state != State::Closing => {
                (peer.state, peer.name.clone().unwrap_or_default())
            }
            _ => return None,
        };
        if !envelope.is_current() {
            let error = BusError::new(
                BusErrorCode::InvalidPayload,
                format!("unsupported protocol version {}", envelope.version),
            );
            self.reject(from, name, error, envelope.id);
            return None;
        }
        Some((state, name))
    }

    /// Handles the first frame of a connection that is still handshaking.
    ///
    /// # Arguments
    /// * `from` - Handshaking connection.
    /// * `origin_name` - Name currently registered for it, if any.
    /// * `envelope` - First frame received from the connection.
    fn route_hello(&mut self, from: PeerId, origin_name: &str, envelope: &Envelope) {
        let request = envelope.target == Target::Router && envelope.kind == Kind::Request;
        let hello = request.then(|| envelope.control()).flatten();
        if let Some(Control::Hello { name }) = hello {
            let _ = self.hello(from, name);
            return;
        }
        let error = BusError::new(
            BusErrorCode::InvalidTarget,
            "first frame must be a hello request to the router",
        );
        self.reject(from, origin_name.to_string(), error, envelope.id);
        if let Some(peer) = self.peers.get_mut(&from) {
            peer.state = State::Closing;
        }
    }

    /// Routes a frame from a fully registered connection.
    ///
    /// # Arguments
    /// * `from` - Sending connection.
    /// * `origin_name` - Registered name of the sender.
    /// * `envelope` - Frame whose `source` has already been stamped.
    fn route_ready(&mut self, from: PeerId, origin_name: PeerName, envelope: Envelope) {
        if envelope.kind == Kind::Response {
            self.route_response(from, envelope);
            return;
        }
        if envelope.target == Target::Router {
            self.route_control(from, origin_name, envelope);
            return;
        }
        match envelope.kind {
            Kind::Request => self.route_request(from, origin_name, envelope),
            Kind::Event => self.route_event(from, origin_name, envelope),
            Kind::Response | Kind::Error => {}
        }
    }

    /// Handles request frames addressed to the router.
    ///
    /// # Arguments
    /// * `from` - Sending connection.
    /// * `origin_name` - Registered name of the sender.
    /// * `envelope` - Router control frame.
    fn route_control(&mut self, from: PeerId, origin_name: PeerName, envelope: Envelope) {
        match (envelope.kind, envelope.control()) {
            (Kind::Request, Some(Control::Subscribe { topic })) => {
                let _ = self.subscribe(from, topic);
            }
            (Kind::Request, Some(Control::Unsubscribe { topic })) => {
                let _ = self.unsubscribe(from, &topic);
            }
            _ => {
                let error = BusError::new(
                    BusErrorCode::InvalidPayload,
                    "unsupported router control frame",
                );
                self.reject(from, origin_name, error, envelope.id);
            }
        }
    }

    /// Delivers a request to one ready peer and records it as pending.
    ///
    /// # Arguments
    /// * `from` - Sending connection.
    /// * `origin_name` - Registered name of the sender.
    /// * `envelope` - Request frame.
    fn route_request(&mut self, from: PeerId, origin_name: PeerName, envelope: Envelope) {
        let Some((target_id, target_name)) = self.request_peer(from, &origin_name, &envelope)
        else {
            return;
        };
        self.pending.insert(
            (target_id, envelope.id),
            Pending {
                origin: from,
                origin_name,
                target_name,
                started: Instant::now(),
            },
        );
        self.push_to(target_id, envelope);
    }

    /// Resolves a request's single-peer target, rejecting invalid targets.
    ///
    /// # Arguments
    /// * `from` - Sending connection.
    /// * `origin_name` - Registered name of the sender.
    /// * `envelope` - Request frame whose target is inspected.
    ///
    /// # Returns
    /// The target connection id and name, or `None` after sending an error.
    fn request_peer(
        &mut self,
        from: PeerId,
        origin_name: &str,
        envelope: &Envelope,
    ) -> Option<(PeerId, PeerName)> {
        let Target::Peer(name) = &envelope.target else {
            let error = BusError::new(
                BusErrorCode::InvalidTarget,
                "requests must address one peer",
            );
            self.reject(from, origin_name.to_string(), error, envelope.id);
            return None;
        };
        let name = name.clone();
        let target = self.names.get(&name).copied();
        let ready = target
            .and_then(|id| self.peers.get(&id))
            .is_some_and(|peer| peer.state == State::Ready);
        if let Some(id) = target.filter(|_| ready) {
            return Some((id, name));
        }
        let error = BusError::new(
            BusErrorCode::PeerUnavailable,
            format!("peer '{name}' is not registered"),
        );
        self.reject(from, origin_name.to_string(), error, envelope.id);
        None
    }

    /// Forwards a response to the origin recorded for `(sender, id)`.
    ///
    /// # Arguments
    /// * `from` - Peer sending the response.
    /// * `envelope` - Response frame correlated by sender and id.
    fn route_response(&mut self, from: PeerId, envelope: Envelope) {
        if let Some(pending) = self.pending.remove(&(from, envelope.id)) {
            self.push_to(pending.origin, envelope);
        }
    }

    /// Delivers an event according to its target selector.
    ///
    /// # Arguments
    /// * `from` - Sending connection.
    /// * `origin_name` - Registered name of the sender.
    /// * `envelope` - Event frame.
    fn route_event(&mut self, from: PeerId, origin_name: PeerName, envelope: Envelope) {
        match envelope.target.clone() {
            Target::Peer(name) => self.route_peer_event(name, envelope),
            Target::Topic(topic) => self.route_topic_event(from, topic, envelope),
            Target::Broadcast => self.route_broadcast_event(from, envelope),
            Target::Router => {
                let error = BusError::new(
                    BusErrorCode::InvalidTarget,
                    "router target is reserved for control frames",
                );
                self.reject(from, origin_name, error, envelope.id);
            }
        }
    }

    /// Delivers an event to one peer, or queues it while the peer is offline.
    ///
    /// # Arguments
    /// * `name` - Name of the target peer.
    /// * `envelope` - Event frame.
    fn route_peer_event(&mut self, name: PeerName, envelope: Envelope) {
        let target = self.names.get(&name).copied();
        let ready = target
            .and_then(|id| self.peers.get(&id))
            .is_some_and(|peer| peer.state == State::Ready);
        if let Some(id) = target.filter(|_| ready) {
            self.push_to(id, envelope);
        } else {
            self.queue_offline(name, envelope);
        }
    }

    /// Fans an event out to subscribers and caches it when retained.
    ///
    /// # Arguments
    /// * `from` - Sending connection, excluded from delivery.
    /// * `topic` - Topic to publish on.
    /// * `envelope` - Event frame.
    fn route_topic_event(&mut self, from: PeerId, topic: Topic, envelope: Envelope) {
        let subscribers: Vec<PeerId> = self
            .peers
            .iter()
            .filter(|(id, peer)| {
                peer.state == State::Ready && **id != from && peer.subscriptions.contains(&topic)
            })
            .map(|(id, _)| *id)
            .collect();
        for id in subscribers {
            self.push_to(id, envelope.clone());
        }
        if envelope.retained {
            self.retain_event(topic, envelope);
        }
    }

    /// Stores a retained event with its effective expiration time.
    ///
    /// # Arguments
    /// * `topic` - Topic whose retained value is replaced.
    /// * `envelope` - Event frame to cache.
    fn retain_event(&mut self, topic: Topic, envelope: Envelope) {
        let now = Instant::now();
        let ttl = envelope
            .ttl_ms
            .map(Duration::from_millis)
            .unwrap_or(RETAINED_TTL);
        self.retained.insert(
            topic,
            Retained {
                envelope,
                expires_at: now.checked_add(ttl).unwrap_or(now),
            },
        );
    }

    /// Fans an event out to every ready peer except the sender.
    ///
    /// # Arguments
    /// * `from` - Sending connection, excluded from delivery.
    /// * `envelope` - Event frame.
    fn route_broadcast_event(&mut self, from: PeerId, envelope: Envelope) {
        let recipients: Vec<PeerId> = self
            .peers
            .iter()
            .filter(|(id, peer)| peer.state == State::Ready && **id != from)
            .map(|(id, _)| *id)
            .collect();
        for id in recipients {
            self.push_to(id, envelope.clone());
        }
    }

    /// Subscribes a peer to a topic and replays the retained value, if any.
    ///
    /// # Arguments
    /// * `id` - Registered connection.
    /// * `topic` - Topic to receive.
    ///
    /// # Errors
    /// Returns [`BusErrorCode::PeerUnavailable`] for an unknown connection or
    /// [`BusErrorCode::InvalidPayload`] before the handshake completes.
    pub fn subscribe(&mut self, id: PeerId, topic: Topic) -> Result<(), BusError> {
        {
            let peer = self.peers.get_mut(&id).ok_or_else(|| {
                BusError::new(BusErrorCode::PeerUnavailable, "unknown connection")
            })?;
            if peer.state != State::Ready {
                return Err(BusError::new(
                    BusErrorCode::InvalidPayload,
                    "peer has not completed the handshake",
                ));
            }
            peer.subscriptions.insert(topic.clone());
        }
        if let Some(retained) = self.retained.get(&topic).cloned() {
            let mut envelope = retained.envelope;
            envelope.retained = true;
            envelope.target = Target::Topic(topic);
            self.push_to(id, envelope);
        }
        Ok(())
    }

    /// Removes one subscription from a peer.
    ///
    /// # Arguments
    /// * `id` - Registered connection.
    /// * `topic` - Topic to stop receiving.
    ///
    /// # Errors
    /// Returns the same errors as [`Self::subscribe`].
    pub fn unsubscribe(&mut self, id: PeerId, topic: &str) -> Result<(), BusError> {
        match self.peers.get_mut(&id) {
            Some(peer) if peer.state == State::Ready => {
                peer.subscriptions.remove(topic);
                Ok(())
            }
            Some(_) => Err(BusError::new(
                BusErrorCode::InvalidPayload,
                "peer has not completed the handshake",
            )),
            None => Err(BusError::new(
                BusErrorCode::PeerUnavailable,
                "unknown connection",
            )),
        }
    }

    /// Takes all frames queued for a connection, leaving the outbox empty.
    pub fn take_outbox(&mut self, id: PeerId) -> Vec<Envelope> {
        self.peers
            .get_mut(&id)
            .map(|peer| std::mem::take(&mut peer.outbox))
            .unwrap_or_default()
    }

    /// Expires pending requests, retained values and offline events.
    ///
    /// # Arguments
    /// * `now` - Current monotonic time supplied by the caller's event loop.
    pub fn tick(&mut self, now: Instant) {
        self.expire_pending(now);
        self.retained.retain(|_, entry| entry.expires_at > now);
        self.expire_offline(now);
    }

    /// Rejects and drops requests older than the response deadline.
    ///
    /// # Arguments
    /// * `now` - Current monotonic time.
    fn expire_pending(&mut self, now: Instant) {
        let expired: Vec<(PeerId, MessageId)> = self
            .pending
            .iter()
            .filter(|(_, pending)| {
                now.saturating_duration_since(pending.started) >= REQUEST_TIMEOUT
            })
            .map(|(key, _)| *key)
            .collect();
        for key in expired {
            if let Some(pending) = self.pending.remove(&key) {
                let error = BusError::new(
                    BusErrorCode::Timeout,
                    format!("request to '{}' timed out", pending.target_name),
                );
                self.reject(pending.origin, pending.origin_name, error, key.1);
            }
        }
    }

    /// Drops expired offline events and their empty queues.
    ///
    /// # Arguments
    /// * `now` - Current monotonic time.
    fn expire_offline(&mut self, now: Instant) {
        for queue in self.offline.values_mut() {
            queue.retain(|entry| entry.expires_at > now);
        }
        self.offline.retain(|_, queue| !queue.is_empty());
    }

    /// Returns the names of all registered peers in stable order.
    pub fn peers(&self) -> Vec<PeerName> {
        self.peers_list()
    }

    /// Returns the names of all registered peers in stable order.
    ///
    /// # Returns
    /// Sorted names of every peer currently owning a name.
    fn peers_list(&self) -> Vec<PeerName> {
        let mut names: Vec<PeerName> = self.names.keys().cloned().collect();
        names.sort();
        names
    }

    /// Allocates the next correlation id.
    ///
    /// # Returns
    /// A freshly generated message id.
    fn next_id(&mut self) -> MessageId {
        let id = self.next_message_id;
        self.next_message_id = self.next_message_id.wrapping_add(1);
        id
    }

    /// Builds a frame stamped with the router as its source.
    ///
    /// # Arguments
    /// * `target` - Destination selector.
    /// * `kind` - Semantic class of the frame.
    /// * `payload` - JSON body.
    ///
    /// # Returns
    /// A new router-generated envelope.
    fn generated(&mut self, target: Target, kind: Kind, payload: serde_json::Value) -> Envelope {
        let mut envelope = Envelope::new(self.next_id(), target, kind, payload);
        envelope.source = ROUTER_SOURCE.to_string();
        envelope
    }

    /// Appends a frame to a peer's outbox when it still exists.
    ///
    /// # Arguments
    /// * `id` - Destination connection.
    /// * `envelope` - Frame to queue.
    fn push_to(&mut self, id: PeerId, envelope: Envelope) {
        if let Some(peer) = self.peers.get_mut(&id) {
            peer.outbox.push(envelope);
        }
    }

    /// Queues an error frame answering the origin of a failed frame.
    ///
    /// # Arguments
    /// * `origin` - Connection that receives the error.
    /// * `origin_name` - Name used as the error frame's target.
    /// * `error` - Failure to report.
    /// * `id` - Correlation id of the failed frame.
    fn reject(&mut self, origin: PeerId, origin_name: PeerName, error: BusError, id: MessageId) {
        let Ok(payload) = serde_json::to_value(&error) else {
            return;
        };
        let mut envelope = self.generated(Target::Peer(origin_name), Kind::Error, payload);
        envelope.id = id;
        self.push_to(origin, envelope);
    }

    /// Publishes a control event to subscribers of a topic.
    ///
    /// # Arguments
    /// * `topic` - Topic to publish on.
    /// * `control` - Control payload to deliver.
    /// * `except` - Connection excluded from delivery, if any.
    fn publish_control(&mut self, topic: Topic, control: Control, except: Option<PeerId>) {
        let Ok(payload) = serde_json::to_value(&control) else {
            return;
        };
        let envelope = self.generated(Target::Topic(topic.clone()), Kind::Event, payload);
        let subscribers: Vec<PeerId> = self
            .peers
            .iter()
            .filter(|(id, peer)| {
                peer.state == State::Ready
                    && Some(**id) != except
                    && peer.subscriptions.contains(&topic)
            })
            .map(|(id, _)| *id)
            .collect();
        for id in subscribers {
            self.push_to(id, envelope.clone());
        }
    }

    /// Queues an event for an absent peer, evicting the oldest on overflow.
    ///
    /// # Arguments
    /// * `name` - Name of the absent peer.
    /// * `envelope` - Event frame to hold.
    fn queue_offline(&mut self, name: PeerName, envelope: Envelope) {
        let now = Instant::now();
        let ttl = envelope
            .ttl_ms
            .map(Duration::from_millis)
            .unwrap_or(OFFLINE_TTL);
        let expires_at = now.checked_add(ttl).unwrap_or(now);
        let queue = self.offline.entry(name).or_default();
        queue.retain(|entry| entry.expires_at > now);
        if queue.len() >= OFFLINE_LIMIT {
            queue.remove(0);
        }
        queue.push(Offline {
            envelope,
            expires_at,
        });
    }

    /// Delivers unexpired events queued for a peer that just registered.
    ///
    /// # Arguments
    /// * `id` - Newly registered connection.
    /// * `name` - Name whose offline queue is drained.
    fn flush_offline(&mut self, id: PeerId, name: &str) {
        let Some(queue) = self.offline.remove(name) else {
            return;
        };
        let now = Instant::now();
        for entry in queue {
            if entry.expires_at > now {
                self.push_to(id, entry.envelope);
            }
        }
    }
}
