//! State owned by the router: peer records, correlation entries and caches.

use std::collections::{HashMap, HashSet};
use std::time::{Duration, Instant};

use common::protocol::{Envelope, MessageId, PeerId, PeerName, Topic};

/// Default lifetime of an event queued for an unknown peer.
pub(super) const OFFLINE_TTL: Duration = Duration::from_secs(30);
/// Default lifetime of a retained topic value.
pub(super) const RETAINED_TTL: Duration = Duration::from_secs(30);
/// Maximum number of queued events per absent peer.
pub(crate) const OFFLINE_LIMIT: usize = 32;
/// Source stamped on frames generated by the router itself.
pub(super) const ROUTER_SOURCE: &str = "router";

// Re-exported so protocol tests can import it from the router as before.
pub(crate) use common::protocol::PEERS_TOPIC;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum State {
    AwaitingHello,
    Ready,
    Closing,
}

#[derive(Debug)]
pub(super) struct Peer {
    pub(super) name: Option<PeerName>,
    pub(super) state: State,
    pub(super) subscriptions: HashSet<Topic>,
    pub(super) outbox: Vec<Envelope>,
}

#[derive(Debug)]
pub(crate) struct Pending {
    pub(super) origin: PeerId,
    pub(super) origin_name: PeerName,
    pub(super) target_name: PeerName,
    pub(super) started: Instant,
}

#[derive(Debug)]
pub(super) struct Offline {
    pub(super) envelope: Envelope,
    pub(super) expires_at: Instant,
}

#[derive(Debug, Clone)]
pub(super) struct Retained {
    pub(super) envelope: Envelope,
    pub(super) expires_at: Instant,
}

/// State machine that routes envelopes between registered peers.
#[derive(Debug)]
pub struct Router {
    pub(super) next_peer_id: PeerId,
    pub(super) next_message_id: MessageId,
    pub(super) peers: HashMap<PeerId, Peer>,
    pub(super) names: HashMap<PeerName, PeerId>,
    pub(crate) pending: HashMap<(PeerId, MessageId), Pending>,
    pub(super) retained: HashMap<Topic, Retained>,
    pub(super) offline: HashMap<PeerName, Vec<Offline>>,
}
